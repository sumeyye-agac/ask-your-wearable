def two_weeks_summary() -> dict:
    """A real weekly_summary result: 7 nights of 7 h 30 min."""
    import pandas as pd
    from wearable.registry import run_tool
    from wearable.schema import to_daily_frame
    df = to_daily_frame(pd.DataFrame({"date": pd.date_range("2016-05-05", periods=7),
                                      "minutes_asleep": [450.0] * 7}))
    return run_tool(df, "weekly_summary", {"metric": "minutes_asleep", "threshold": 420})


