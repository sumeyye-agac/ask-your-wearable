@pytest.fixture(autouse=True)
def fresh_app(monkeypatch, tmp_path):
    # A set but empty key stops load_dotenv from reading a real key out of .env.
    monkeypatch.setenv("ANTHROPIC_API_KEY", "")
    # Keep test runs out of the real logs/trace.jsonl.
    monkeypatch.setenv("WEARABLE_TRACE", str(tmp_path / "trace.jsonl"))
    st.cache_data.clear()
    st.cache_resource.clear()
    yield
    st.cache_resource.clear()


def pick_example(at: AppTest, index: int = 0) -> AppTest:
    """Click an example pill: it fills the question box and sends nothing."""
    pills = at.button_group(key="example")
    pills.set_value(pills.options[index]).run()
    return at


def run_example(at: AppTest, index: int = 0) -> AppTest:
    """Click an example pill, then press Ask."""
    pick_example(at, index)
    press_ask(at)
    return at


def press_ask(at: AppTest) -> AppTest:
    at.button(key="ask_button").click().run()
    return at


def pick(at: AppTest, user_id: str) -> AppTest:
    at.button_group(key="person").set_value(user_id).run()
    return at


def stub_ask(monkeypatch, result=None, error=None) -> list[str]:
    """Replace the agent; returns the list of questions it receives."""
    asked: list[str] = []

    def fake(client, df, question, **kwargs):
        asked.append(question)
        if error is not None:
            raise error
        result.question = question
        return result
    monkeypatch.setattr(wearable.agent, "ask", fake)
    monkeypatch.setenv("ANTHROPIC_API_KEY", "test-key-not-used")
    return asked


def simple_result(answer="Fine.") -> AgentResult:
    return AgentResult(question="", answer=answer, status="answered",
                       model="claude-haiku-5-5", steps=1)


def type_and_submit(at: AppTest, text: str) -> AppTest:
    at.text_input(key="question").set_value(text)
    return press_ask(at)


def shown_question(at: AppTest) -> str:
    """The visitor's question: the text right under the "Your question" label."""
    values = [m.value for m in at.markdown]
    return values[next(i for i, v in enumerate(values) if ">Your question" in v) + 1]


def example_is_shown(at: AppTest) -> bool:
    return any(">Example answer" in m.value for m in at.markdown)


