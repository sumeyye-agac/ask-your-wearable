def test_page_has_no_sidebar_info_box_or_bordered_buttons():
    at = AppTest.from_file(APP).run()
    assert not at.sidebar.children
    assert not at.info
    assert not [b for b in at.button if b.key and str(b.key).startswith("example")]
    forms = []

    def walk(node):
        for child in getattr(node, "children", {}).values():
            proto = getattr(child, "proto", None)
            if type(proto).__name__ == "Block" and proto.HasField("form"):
                forms.append(proto.form)
            walk(child)
    walk(at._tree)
    assert [f.form_id for f in forms] == ["ask"] and forms[0].border is False


